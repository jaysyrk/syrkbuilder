    private PixelFont() {
    }

    private static void put(char c, String... rows) {
        GLYPHS.put(c, rows);
    }

    public static boolean supports(char c) {
        return GLYPHS.containsKey(Character.toUpperCase(c));
    }

    public interface Pixel {
        void at(int column, int row);
    }

    public static int render(String text, Pixel pixel) {
        int x = 0;
        for (char raw : text.toUpperCase(Locale.ROOT).toCharArray()) {
            String[] rows = GLYPHS.getOrDefault(raw, GLYPHS.get('?'));
            int width = rows[0].length();
            for (int row = 0; row < HEIGHT; row++) {
                for (int col = 0; col < width; col++) {
                    if (col < rows[row].length() && rows[row].charAt(col) == '#') {
                        pixel.at(x + col, HEIGHT - 1 - row);
                    }
                }
            }
            x += width + 1;
        }
        return Math.max(0, x - 1);
    }
